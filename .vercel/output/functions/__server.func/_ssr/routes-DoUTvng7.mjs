function measure(offerings) {
	const occ = new Array(40).fill(false);
	let clashes = 0;
	for (const o of offerings) for (const c of o.cells) {
		if (occ[c]) clashes += 1;
		occ[c] = true;
	}
	let gaps = 0;
	let daysUsed = 0;
	let morning = 0;
	let total = 0;
	for (let d = 0; d < 5; d++) {
		const am = [];
		const pm = [];
		for (let p = 0; p < 8; p++) {
			if (!occ[d * 8 + p]) continue;
			total += 1;
			if (isMorning(p)) {
				morning += 1;
				am.push(p);
			} else pm.push(p);
		}
		if (am.length || pm.length) daysUsed += 1;
		const spanGaps = (xs) => xs.length ? xs[xs.length - 1] - xs[0] + 1 - xs.length : 0;
		gaps += spanGaps(am) + spanGaps(pm);
	}
	const credits = offerings.reduce((s, o) => s + o.credits, 0);
	const aimlScore = offerings.reduce((s, o) => s + o.aimlScore * o.credits, 0);
	const morningShare = total ? morning / total : 0;
	const compactness = Math.max(0, Math.min(100, 100 - gaps * 9 - Math.max(0, daysUsed - 4) * 4));
	return {
		credits,
		gaps,
		daysUsed,
		morningShare,
		aimlScore,
		compactness,
		clashes
	};
}
function rankScore(planLike, opts) {
	let s = planLike.aimlScore - planLike.gaps * 48 - planLike.clashes * 500;
	if (opts.preferMorning) s += planLike.morningShare * 80;
	if (planLike.credits >= 25) s += 12;
	s += planLike.compactness * .6;
	return s;
}
